-- Тип ENUM для категорий меню
CREATE TYPE menu_category AS ENUM (
    'Выпечка',
    'Горячее',
    'Гриль',
    'Закуски',
    'Соусы',
    'Десерты',
    'Супы',
    'Напитки'
);

-- Тип ENUM для зон ресторана
CREATE TYPE table_location AS ENUM (
    'Зал у окна',
    'Терраса',
    'VIP-зал',
    'Основной зал'
);

-- Тип ENUM для ролей персонала
CREATE TYPE staff_role AS ENUM (
    'Официант',
    'Шеф-повар',
    'Повар',
    'Администратор',
    'Бармен'
);

-- Измерение: Дата
CREATE TABLE dim_date (
    DateKey     INT PRIMARY KEY,
    FullDate    DATE NOT NULL,
    Month       INT NOT NULL,
    Year        INT NOT NULL,
    DayName     VARCHAR(20) NOT NULL
);
ALTER TABLE dim_date
    ADD CONSTRAINT CHK_Month CHECK (Month BETWEEN 1 AND 12),
    ADD CONSTRAINT CHK_Year  CHECK (Year BETWEEN 2000 AND 2100);

-- Измерение: Клиент
CREATE TABLE dim_customer (
    CustomerKey INT PRIMARY KEY,
    FirstName   VARCHAR(100) NOT NULL,
    LastName    VARCHAR(100) NOT NULL,
    Phone       VARCHAR(20)
);
ALTER TABLE dim_customer
ADD CONSTRAINT UQ_CustomerPhone UNIQUE (Phone);

-- Измерение: Блюдо меню
CREATE TABLE dim_menu_item (
    MenuItemKey  INT PRIMARY KEY,
    Name         VARCHAR(100) NOT NULL,
    Category     menu_category NOT NULL,
    CurrentPrice DECIMAL(8,2) NOT NULL
);
ALTER TABLE dim_menu_item
ADD CONSTRAINT CHK_Price CHECK (CurrentPrice >= 0);

-- Измерение: Стол
CREATE TABLE dim_table (
    TableKey    INT PRIMARY KEY,
    TableNumber INT NOT NULL,
    Capacity    INT NOT NULL,
    Location    table_location NOT NULL
);
ALTER TABLE dim_table
ADD CONSTRAINT UQ_TableNumber UNIQUE (TableNumber),
    ADD CONSTRAINT CHK_TableNumber CHECK (TableNumber > 0),
    ADD CONSTRAINT CHK_Capacity CHECK (Capacity > 0 AND Capacity <= 20);
    
-- Измерение: Персонал
CREATE TABLE dim_staff (
    StaffKey  INT PRIMARY KEY,
    FirstName VARCHAR(100) NOT NULL,
    LastName  VARCHAR(100) NOT NULL,
    Role      staff_role NOT NULL
);

CREATE TABLE Fact_Orders (
    OrderItemKey  INT PRIMARY KEY,
    DateKey       INT NOT NULL,
    CustomerKey   INT NOT NULL,
    MenuItemKey   INT NOT NULL,
    TableKey      INT NOT NULL,
    WaiterKey     INT NOT NULL,
    Quantity      INT NOT NULL,
    UnitPrice     DECIMAL(8,2) NOT NULL,

    CONSTRAINT FK_DateKey FOREIGN KEY (DateKey)    		 REFERENCES dim_date(DateKey),
    CONSTRAINT FK_CustomerKey FOREIGN KEY (CustomerKey)  REFERENCES dim_customer(CustomerKey),
    CONSTRAINT FK_MenuItemKey FOREIGN KEY (MenuItemKey)  REFERENCES dim_menu_item(MenuItemKey),
    CONSTRAINT FK_TableKey FOREIGN KEY (TableKey)    	 REFERENCES dim_table(TableKey),
    CONSTRAINT FK_WaiterKey FOREIGN KEY  (WaiterKey)     REFERENCES dim_staff(StaffKey)
);

ALTER TABLE Fact_Orders
    ADD CONSTRAINT CHK_Quantity CHECK (Quantity > 0),
    ADD CONSTRAINT CHK_UnitPrice CHECK (UnitPrice >= 0);

